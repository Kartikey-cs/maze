"""Dependency-free ridge regression for measured maze-bot success rates."""
import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

FEATURES = ["vertices", "edges", "dead_ends", "junctions", "loops",
            "shortest_path", "detour_ratio"]
RIDGE = 0.001


def split_seeds(rows):
    """Hold out every fifth seed, including all difficulties for that seed."""
    training = [r for r in rows if r["seed"] % 5 != 0]
    testing = [r for r in rows if r["seed"] % 5 == 0]
    if not training or not testing:
        raise ValueError("Dataset must contain both training and held-out seeds")
    return training, testing


def solve(matrix, target):
    """Pivoted elimination of the small, ridge-regularized normal equations."""
    augmented = [row[:] + [value] for row, value in zip(matrix, target, strict=True)]
    n = len(target)
    for col in range(n):
        pivot = max(range(col, n), key=lambda r: abs(augmented[r][col]))
        augmented[col], augmented[pivot] = augmented[pivot], augmented[col]
        divisor = augmented[col][col]
        if abs(divisor) < 1e-15:
            raise ValueError("Singular fit")
        augmented[col] = [value / divisor for value in augmented[col]]
        for row in range(n):
            if row != col:
                factor = augmented[row][col]
                augmented[row] = [a - factor*b for a, b in
                                  zip(augmented[row], augmented[col], strict=True)]
    return [row[-1] for row in augmented]


def fit(x, y):
    n, width = len(x), len(x[0])
    mean = [sum(row[j] for row in x) / n for j in range(width)]
    scale = [math.sqrt(sum((row[j]-mean[j])**2 for row in x) / n) or 1.0
             for j in range(width)]
    z = [[(v-m)/s for v, m, s in zip(row, mean, scale, strict=True)] for row in x]
    intercept = sum(y) / n
    covariance = [[sum(row[i]*row[j] for row in z) / n + (RIDGE if i == j else 0)
                   for j in range(width)] for i in range(width)]
    target = [sum(row[j]*(label-intercept) for row, label in zip(z, y, strict=True)) / n
              for j in range(width)]
    return {"mean": mean, "scale": scale, "weights": solve(covariance, target),
            "intercept": intercept}


def predict(model, row):
    score = model["intercept"]
    for value, mean, scale, weight in zip(row, model["mean"], model["scale"],
                                         model["weights"], strict=True):
        score += weight * ((value - mean) / scale)
    return min(1.0, max(0.0, score))


def mse(model, x, y):
    return sum((predict(model, row)-label)**2 for row, label in zip(x, y, strict=True)) / len(y)


def export_header(model, path):
    def array(name, values):
        return f"    static const double {name}[] = {{" + ", ".join(format(v, ".17g") for v in values) + "};\n"
    content = ("/* Generated by tools/train_model.py. Feature order: " + ", ".join(FEATURES) + ". */\n"
               "#ifndef MAZE_MODEL_H\n#define MAZE_MODEL_H\n"
               f"#define MAZE_MODEL_FEATURE_COUNT {len(FEATURES)}\n"
               "/* Estimated success rate for an equal mixture of the two simulated bots. */\n"
               "static inline double MazeModel_PredictSuccess(const double features[MAZE_MODEL_FEATURE_COUNT])\n{\n")
    for name in ("mean", "scale", "weights"):
        content += array(name, model[name])
    content += (f"    double score = {model['intercept']:.17g};\n"
                "    for (int i = 0; i < MAZE_MODEL_FEATURE_COUNT; i++)\n"
                "        score += weights[i] * ((features[i] - mean[i]) / scale[i]);\n"
                "    return score < 0.0 ? 0.0 : (score > 1.0 ? 1.0 : score);\n}\n#endif\n")
    Path(path).write_text(content)


def load_rows(path):
    with Path(path).open(newline="") as source:
        rows = list(csv.DictReader(source))
    seen = set()
    for row in rows:
        row["seed"] = int(row["seed"])
        row["difficulty"] = int(row["difficulty"])
        key = row["seed"], row["difficulty"]
        if key in seen or not 0 < key[0] <= 2**32-1 or key[1] not in range(3):
            raise ValueError("Invalid or duplicate maze seed/difficulty")
        seen.add(key)
        for name in FEATURES + ["success_rate"]:
            row[name] = float(row[name])
            if not math.isfinite(row[name]) or row[name] < 0:
                raise ValueError(f"Invalid {name}")
        trials = int(row["trials_per_bot"])
        successes = [int(row[name]) for name in ("random_successes", "greedy_successes")]
        if trials <= 0 or any(not 0 <= s <= trials for s in successes) or not math.isclose(
                row["success_rate"], sum(successes)/(2*trials), abs_tol=1e-12):
            raise ValueError("Success label does not match simulation counts")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--output", type=Path, default=Path("model"))
    args = parser.parse_args()
    rows = load_rows(args.dataset)
    training, testing = split_seeds(rows)
    vectors = lambda group: [[r[name] for name in FEATURES] for r in group]
    baseline_vectors = lambda group: [[r["shortest_path"] + r["dead_ends"]] for r in group]
    labels = lambda group: [r["success_rate"] for r in group]
    model = fit(vectors(training), labels(training))
    baseline = fit(baseline_vectors(training), labels(training))
    model_error = mse(model, vectors(testing), labels(testing))
    baseline_error = mse(baseline, baseline_vectors(testing), labels(testing))
    verdict = "Model beats baseline" if model_error < baseline_error else "Model does not beat baseline"
    report = {"dataset_sha256": hashlib.sha256(args.dataset.read_bytes()).hexdigest(),
              "split": "seed % 5 == 0 held out; all difficulties grouped by seed",
              "train_seeds": sorted({r["seed"] for r in training}),
              "test_seeds": sorted({r["seed"] for r in testing}),
              "train_rows": len(training), "test_rows": len(testing), "ridge": RIDGE,
              "test_mse": model_error, "baseline_test_mse": baseline_error,
              "baseline": {"feature": "shortest_path + dead_ends", **baseline},
              "verdict": verdict}
    args.output.mkdir(parents=True, exist_ok=True)
    export_header(model, args.output / "maze_model.h")
    (args.output / "maze_model.json").write_text(json.dumps({"features": FEATURES, **model}, indent=2) + "\n")
    (args.output / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"Held-out MSE: model={model_error:.8f}, baseline={baseline_error:.8f}. {verdict}.")


if __name__ == "__main__":
    main()
